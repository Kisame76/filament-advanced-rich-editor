<?php

declare(strict_types=1);

namespace Kisame76\FilamentAdvancedRichEditor\RichEditor\Plugins;

use Filament\Actions\Action;
use Filament\Forms\Components\RichEditor\Plugins\Contracts\RichContentPlugin;
use Filament\Forms\Components\RichEditor\RichEditorTool;
use Filament\Support\Facades\FilamentAsset;
use Tiptap\Core\Extension;

/**
 * The toolbar on a touch screen while the keyboard is up: docked on the keyboard, and a tap
 * on a button that keeps the keyboard where it is.
 *
 * Nothing is stored and nothing is drawn but a class. Registered on every field, because only
 * the browser knows whether it is held by a finger - the script stops at once on a mouse. The
 * rest of what a finger needs, bigger buttons and a bar that scrolls sideways, is the
 * stylesheet's. See `resources/js/touch-toolbar.js`.
 */
class TouchToolbarPlugin implements RichContentPlugin
{
    public static function make(): static
    {
        return app(static::class);
    }

    /**
     * @return array<Extension>
     */
    public function getTipTapPhpExtensions(): array
    {
        return [];
    }

    /**
     * @return array<string>
     */
    public function getTipTapJsExtensions(): array
    {
        return [
            FilamentAsset::getScriptSrc('advanced-rich-editor/touch-toolbar', 'kisame76/filament-advanced-rich-editor'),
        ];
    }

    /**
     * @return array<RichEditorTool>
     */
    public function getEditorTools(): array
    {
        return [];
    }

    /**
     * @return array<Action>
     */
    public function getEditorActions(): array
    {
        return [];
    }
}
